//! 코퍼스 실행기 겸 채점기.
//!
//! 두 가지를 한다.
//!
//! 1. **코퍼스 대조** — `corpus/cases/<이름>/` 의 입력을 돌려 채널별 기대 출력과 맞춰 본다.
//! 2. **불변식 채점** — 기대 출력이 없어도 잴 수 있는 것들을 잰다.
//!
//! 재는 축은 **"채널이 받아 주는가"가 아니라 "저자가 쓴 것이 살아남는가"**다. 채널은
//! 틀려도 200 을 주기 때문에(`DESIGN.md`) 받아 준다는 사실 자체는 아무것도 보증하지 않는다.
//! 강조 범위가 원문과 같은가, 마커가 글자로 새지 않았는가, 그리고 **내용이 사라지지
//! 않았는가** — 마지막 것은 한도를 분할이 아니라 절단으로 다루는 구현이 다른 모든 규칙을
//! 통과하면서 뒤쪽을 통째로 버리기 때문에 따로 둔다.
//!
//! 2가 있는 이유는 1만으로는 **자기채점**이기 때문이다. 기대 출력은 우리가 만든 것이고,
//! 우리 구현이 틀린 채로 기대 출력을 만들면 영원히 통과한다. 그래서 어느 구현에나 똑같이
//! 적용되는 잣대를 따로 둔다 — 짝 안 맞는 마커, 안 닫힌 태그, 한도 초과, 표 열 어긋남,
//! 그리고 **강조 범위가 원문과 같은가**.
//!
//! 채점 대상은 [`adapter::Renderer`] 로 붙인다. 요구하는 것은 **문자열 in → 문자열 out**
//! 하나뿐이라, 다른 언어로 쓰인 구현도 [`adapter::Command`] 로 같은 잣대에 올릴 수 있다.
//!
//! 입력은 코퍼스 밖에서도 받는다 — [`corpus::scan_dir`] 는 디렉토리를 훑어 불변식만 잰다.
//! 실제 에이전트 문서로 잴 때 쓴다. **그 문서들은 이 저장소에 넣지 않는다.**

