// CharWidth returns the display width of one character: 0, 1 or 2.
func CharWidth(c rune) int {
	if c == 0 {
		return 0
	}
	if c < 0x20 || (c >= 0x7F && c < 0xA0) {
		// 제어 문자. 표에 들어오면 폭 계산이 무너지므로 0 으로 센다.
		return 0
	}
	if c < 0x300 {
		// 라틴 상용 구간. 표 대부분이 여기라 먼저 끊는다.
		return 1
	}
	if inSpans(zeroWidth, c) {
		return 0
	}
	if inSpans(wide, c) {
		return 2
	}
	return 1
}

// StrWidth returns the display width of a string. Emoji ZWJ sequences count
// each component separately, so the result can be wider than the actual
// display. This errs toward extra space rather than misaligned tables, so it
// is left as is.
func StrWidth(s string) int {
	n := 0
	for _, c := range s {
		n += CharWidth(c)
	}
	return n
}

// inSpans 는 이진 탐색이다. 구간표가 정렬·비중첩이라는 전제는 테스트가 지킨다.
func inSpans(table []cpRange, c rune) bool {
	lo, hi := 0, len(table)
	for lo < hi {
		mid := (lo + hi) / 2
		s := table[mid]
		switch {
		case c < s.lo:
			hi = mid
		case c > s.hi:
			lo = mid + 1
		default:
			return true
		}
	}
	return false
}
